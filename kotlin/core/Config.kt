package voxgig.smsapisdk.core

import voxgig.smsapisdk.utility.Json

/** Static SDK configuration and by-name feature construction. */
@Suppress("UNCHECKED_CAST")
object Config {

  fun makeConfig(): MutableMap<String, Any?> {
    return Json.parse(configJson()) as MutableMap<String, Any?>
  }

  // SHARED CONFIG (sdkgen rung L2).
  //
  // The SDK reads the config on every request and never writes to it, so one
  // instance is shared by every client rather than rebuilt per client - the
  // difference between parsing the embedded JSON once and once per client.
  //
  // 'by lazy' defaults to LazyThreadSafetyMode.SYNCHRONIZED, so concurrent
  // first calls build it exactly once.
  //
  // The returned map is SHARED: treat it as read-only. Callers that need to
  // mutate should use makeConfig, which always parses a fresh copy.
  private val sharedConfigVal: MutableMap<String, Any?> by lazy { makeConfig() }

  fun sharedConfig(): MutableMap<String, Any?> = sharedConfigVal

  fun makeFeature(name: String): Feature {
    return when (name) {
      "audit" -> voxgig.smsapisdk.feature.AuditFeature()
      "cache" -> voxgig.smsapisdk.feature.CacheFeature()
      "clienttrack" -> voxgig.smsapisdk.feature.ClienttrackFeature()
      "cost" -> voxgig.smsapisdk.feature.CostFeature()
      "debug" -> voxgig.smsapisdk.feature.DebugFeature()
      "idempotency" -> voxgig.smsapisdk.feature.IdempotencyFeature()
      "log" -> voxgig.smsapisdk.feature.LogFeature()
      "metrics" -> voxgig.smsapisdk.feature.MetricsFeature()
      "netsim" -> voxgig.smsapisdk.feature.NetsimFeature()
      "paging" -> voxgig.smsapisdk.feature.PagingFeature()
      "proxy" -> voxgig.smsapisdk.feature.ProxyFeature()
      "ratelimit" -> voxgig.smsapisdk.feature.RatelimitFeature()
      "rbac" -> voxgig.smsapisdk.feature.RbacFeature()
      "retry" -> voxgig.smsapisdk.feature.RetryFeature()
      "secrets" -> voxgig.smsapisdk.feature.SecretsFeature()
      "streaming" -> voxgig.smsapisdk.feature.StreamingFeature()
      "telemetry" -> voxgig.smsapisdk.feature.TelemetryFeature()
      "test" -> voxgig.smsapisdk.feature.TestFeature()
      "timeout" -> voxgig.smsapisdk.feature.TimeoutFeature()
      "validate" -> voxgig.smsapisdk.feature.ValidateFeature()
      else -> voxgig.smsapisdk.feature.BaseFeature()
    }
  }

